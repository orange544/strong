DROP TABLE IF EXISTS retry_upload_queue;
DROP TABLE IF EXISTS offline_address_book;
DROP TABLE IF EXISTS scan_cache;
DROP TABLE IF EXISTS local_sign_cache;
DROP TABLE IF EXISTS local_task_cache;

CREATE TABLE local_task_cache (
  task_id TEXT PRIMARY KEY,
  task_no TEXT NOT NULL,
  waybill_no TEXT NOT NULL,
  delivery_status TEXT NOT NULL,
  sync_status TEXT NOT NULL
);

CREATE TABLE local_sign_cache (
  sign_id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL,
  sign_time TEXT NOT NULL,
  sign_result TEXT NOT NULL,
  sync_status TEXT NOT NULL
);

CREATE TABLE scan_cache (
  scan_id TEXT PRIMARY KEY,
  package_no TEXT NOT NULL,
  scan_type TEXT NOT NULL,
  scan_time TEXT NOT NULL,
  sync_status TEXT NOT NULL,
  device_id TEXT NOT NULL
);

CREATE TABLE offline_address_book (
  address_id TEXT PRIMARY KEY,
  recipient_name TEXT NOT NULL,
  recipient_phone TEXT NOT NULL,
  detail_address TEXT NOT NULL,
  geo_lng REAL NOT NULL,
  geo_lat REAL NOT NULL
);

CREATE TABLE retry_upload_queue (
  retry_id TEXT PRIMARY KEY,
  biz_type TEXT NOT NULL,
  biz_id TEXT NOT NULL,
  payload_json TEXT NOT NULL,
  retry_count INTEGER NOT NULL,
  next_retry_time TEXT NOT NULL,
  status TEXT NOT NULL
);

CREATE INDEX idx_local_task_cache_waybill_no ON local_task_cache(waybill_no);
CREATE INDEX idx_local_task_cache_sync_status ON local_task_cache(sync_status);

CREATE INDEX idx_local_sign_cache_task_id ON local_sign_cache(task_id);
CREATE INDEX idx_local_sign_cache_sync_status ON local_sign_cache(sync_status);

CREATE INDEX idx_scan_cache_package_no ON scan_cache(package_no);
CREATE INDEX idx_scan_cache_sync_status ON scan_cache(sync_status);

CREATE INDEX idx_offline_address_book_recipient_phone ON offline_address_book(recipient_phone);

CREATE INDEX idx_retry_upload_queue_biz_type ON retry_upload_queue(biz_type);
CREATE INDEX idx_retry_upload_queue_biz_id ON retry_upload_queue(biz_id);
CREATE INDEX idx_retry_upload_queue_next_retry_time ON retry_upload_queue(next_retry_time);
CREATE INDEX idx_retry_upload_queue_status ON retry_upload_queue(status);

